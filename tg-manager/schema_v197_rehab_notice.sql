-- v197: метка «об итоге восстановления уже сообщили».
--
-- Авто-реабилитация (services/account_rehab) сутками возвращает в строй
-- аккаунты со спам-блоком, а исчерпав попытки — переводит их в фазу `stuck`
-- («нужен ручной разбор»). Обе новости не доходили до владельца вообще:
-- вернувшийся аккаунт человек успевал списать и заменить, а «переданный на
-- ручной разбор» вставал в очередь, которую некому было увидеть.
--
-- Метка хранит фазу, о которой уже сообщили: об одном итоге пишем один раз,
-- но повторное восстановление того же аккаунта позже будет объявлено снова.
ALTER TABLE account_rehab_state
    ADD COLUMN IF NOT EXISTS notified_phase TEXT;

-- Выборка «есть о чём сообщить» — по завершённым и ещё не объявленным.
CREATE INDEX IF NOT EXISTS idx_rehab_unannounced
    ON account_rehab_state(owner_id)
 WHERE phase IN ('freed', 'stuck');
