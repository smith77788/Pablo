-- schema_v386: у строки ленты уведомлений появляется дверь.
--
-- Лента (schema_v385) показывала текст: «Операция #412 завершена», «Аккаунт
-- ограничен». Открыть то, о чём уведомление, было нельзя — владелец читал
-- номер и шёл искать его руками через очередь или список аккаунтов. Здесь
-- хранится, куда вести: {"fn": "openOpDetail", "arg": 412} — то же, чем уже
-- присылаются быстрые действия по итогу операции.
--
-- jsonb, а не две колонки: у разных событий разные цели (операция, аккаунт,
-- бот, контакт), и колонка под каждую означала бы таблицу с пустотами.
ALTER TABLE notification_feed ADD COLUMN IF NOT EXISTS link JSONB;
