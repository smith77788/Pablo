-- schema_v218: счётчик «воскрешений» операции после падения/зависания.
--
-- Зачем. Операции, застрявшие в 'running', возвращались в 'pending' двумя
-- механизмами: сбросом на старте воркера (после SIGTERM/рестарта Railway) и
-- сторожем зависших (running дольше 60 минут). Оба сбрасывали статус БЕЗ
-- какого-либо учёта попыток, поэтому операция, которая РОНЯЕТ или ВЕШАЕТ сам
-- воркер, воскресала бесконечно: упала → рестарт контейнера → снова подхвачена
-- → снова уронила. Каждый круг занимал слот параллельности и забирал аккаунты
-- флота, а владелец видел операцию, которая «всё время выполняется» и никогда
-- не заканчивается.
--
-- retry_count для этого не годится: он расходуется на повторы по ОШИБКЕ
-- исполнителя (FloodWait, сеть) и обнуляться не должен — иначе честный повтор
-- после флуда съедал бы бюджет живучести, и наоборот.
--
-- Аддитивно, с DEFAULT 0: старые строки трактуются как «ни разу не воскресали».
ALTER TABLE operation_queue
    ADD COLUMN IF NOT EXISTS revive_count INT NOT NULL DEFAULT 0;

COMMENT ON COLUMN operation_queue.revive_count IS
    'Сколько раз операцию возвращали в pending после падения/зависания воркера (не по ошибке исполнителя — тот счётчик retry_count).';
