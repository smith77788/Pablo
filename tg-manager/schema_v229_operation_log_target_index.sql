-- schema_v229: индекс operation_log по цели, под движок иммунитета.
--
-- operation_log — самая большая таблица продукта: строка на каждую цель
-- каждой массовой операции, хранится 30 дней. Индексов было два: по op_id
-- (по нему читают ход конкретной операции) и по created_at (по нему уборка).
--
-- Движок иммунитета (services/immunity_engine.py) читает её ИНАЧЕ — по цели:
-- на каждое событие смерти или изменения статуса аккаунта он собирает окно
-- «что этот аккаунт делал за 72 часа до» (`WHERE l.target=$1 AND l.created_at
-- между`), а на смерть ещё и сравнивает с выжившими той же гео — join по
-- `l.target = a.id::text`. Ведущей колонки target не было ни в одном индексе,
-- поэтому каждый такой запрос читал таблицу целиком.
--
-- Замер на живом Postgres, 300 000 строк: 29.5 мс против 0.4 мс с индексом —
-- в семьдесят раз. Цикл иммунитета крутится раз в две минуты и берёт до ста
-- событий за проход, а таблица растёт линейно объёму массовых операций, так
-- что на реальном флоте это единицы секунд процессорного времени базы на
-- каждый проход, и они уходят целиком.
--
-- Порядок колонок (target, created_at): равенство по цели, затем диапазон по
-- времени — окно берётся прямо из индекса.

CREATE INDEX IF NOT EXISTS idx_operation_log_target_created
    ON operation_log (target, created_at);
