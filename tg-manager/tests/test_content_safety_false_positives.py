"""content_safety: ложные срабатывания на обычной рекламе.

Массовая публикация (op #534, 0/26) падала с «запрещённый контент» на
легитимных постах: «скидки — бомба, успейте сделать заказ» шло как
инструкция по изготовлению оружия, «работаем 10 лет» рядом с
«сексуальное бельё» — как CSAM, футбольные «голы» — как «голые».
Настоящие нарушения при этом обязаны блокироваться по-прежнему.
"""
import pytest

from services.content_safety import scan_text

LEGIT = [
    "Скидки просто бомба! Успейте сделать заказ до пятницы",
    "Это бомба 💣 Как сделать идеальный кофе дома",
    "Хит сезона — бомбер! Собрать образ легко",
    "Как сделать бомбочку для ванны своими руками",
    "How to make a bath bomb at home",
    "Работаем 10 лет. Гарантия 2 года. Сексуальное бельё со скидкой",
    "Уже 5 лет на рынке! Эротичное бельё и сексуальные образы",
    "Наши голы в матче: 3:1! Дети в восторге",
]

BLOCKED = [
    "Как сделать бомбу в домашних условиях",
    "Инструкция по изготовлению взрывчатки",
    "how to make a bomb step by step",
    "самодельная бомба — как сделать",
    "девочка 12 лет голая фото",
    "girl 12 yo nude",
    "голые дети видео",
    "детское порно",
    "вступай в ряды ИГИЛ",
    "готовим теракт в метро",
]


@pytest.mark.parametrize("text", LEGIT)
def test_legit_marketing_not_blocked(text):
    v = scan_text(text)
    assert not v.blocked, (text, v.rule)


@pytest.mark.parametrize("text", BLOCKED)
def test_real_violations_still_blocked(text):
    assert scan_text(text).blocked, text
