"""Храповик: имя, которого нет, не доезжает до прода.

За один разбор в ветке нашлось шесть мест, где код обращается к
несуществующему имени. Все шесть — не опечатки в мёртвом коде, а живые пути:

* `bot/handlers/accounts.py` — `story_manager` импортировался ВНУТРИ одной
  функции, а использовался в трёх соседних: кнопки «читать сторис», «экспорт»
  и «удалить все» падали с NameError при нажатии;
* `services/broadcaster.py` — `log_exc_swallow(log, …)` при отсутствующем
  `log`: падала сама ветка обработки ошибки, то есть проглоченная ошибка
  превращалась в необработанную;
* `services/op_worker.py` — `_exec_global_presence_channel` захватывал пул по
  `accounts_rows` ДО того, как эта переменная появлялась: операция падала, не
  создав ни одного канала;
* `services/mini_app_api.py` — локальная переменная `_err` затирала функцию
  ответа об ошибке `_err(msg, status)` на всю `user_settings_save`: ветка 401
  падала с UnboundLocalError, ветка 500 — с TypeError.

Синтаксис такие вещи не ловит, импорт модуля тоже: имя разрешается в момент
ИСПОЛНЕНИЯ строки. Поэтому проверка статическая, по тем правилам ruff, которые
говорят ровно об этом классе и не имеют ложных срабатываний на этом коде.
Стилевые правила сюда НЕ добавлять: у них ложные срабатывания
(`add_bot()` возвращает `bool | str`, и `!= True` там осмысленно), а храповик с
ложными срабатываниями выключают целиком.
"""
from __future__ import annotations

import os
import shutil
import subprocess

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Каждое правило — про несуществующее или неготовое имя, не про стиль.
RULES = [
    "F821",  # обращение к неопределённому имени
    "F822",  # неопределённое имя в __all__
    "F823",  # обращение к локальной переменной до присваивания
    "F601",  # повторяющийся ключ словаря — одно из значений молча теряется
    "F602",  # то же для ключа-переменной
    "F632",  # `is` с литералом — сравнение, которое не работает
    "F702",  # continue вне цикла
    "E711",  # сравнение с None через ==
    "E714",  # not ... is ... вместо is not
    "F502",  # % с dict вместо tuple
    "F506",  # смешение позиционных и именованных в %
    "F522",  # .format() с неизвестным ключом
    "F901",  # raise NotImplemented вместо NotImplementedError
]


def test_ruff_is_available():
    """Отдельным тестом, чтобы отсутствие ruff было видно как отсутствие ruff.

    Иначе проверка ниже пропускалась бы, и храповик молча перестал бы держать.
    """
    assert shutil.which("ruff"), (
        "ruff не установлен, а он держит проверку на несуществующие имена. "
        "Поставьте: pip install -r requirements-dev.txt"
    )


def test_no_undefined_names():
    if not shutil.which("ruff"):
        pytest.fail(
            "ruff не установлен — проверка на несуществующие имена не выполнена. "
            "Поставьте: pip install -r requirements-dev.txt"
        )
    res = subprocess.run(
        ["ruff", "check", ROOT, "--select", ",".join(RULES),
         "--output-format", "concise", "--no-cache"],
        capture_output=True, text=True,
    )
    assert res.returncode == 0, (
        "код обращается к именам, которых в этот момент не существует — "
        "это падение при исполнении строки, а не стилевое замечание:\n"
        + (res.stdout or res.stderr)
    )


def test_story_manager_reachable_from_module_scope():
    """Регрессия: модуль сторис виден ВСЕМ хендлерам файла, а не одному.

    Падает на коде без фикса: раньше `from services import story_manager` стоял
    внутри `handle_story_caption`, поэтому у модуля такого атрибута не было, а
    три другие кнопки обращались к имени, которого в их области нет.
    """
    from bot.handlers import accounts

    assert hasattr(accounts, "story_manager"), (
        "story_manager импортируется внутри одной функции — соседние хендлеры "
        "сторис упадут с NameError при нажатии кнопки"
    )
