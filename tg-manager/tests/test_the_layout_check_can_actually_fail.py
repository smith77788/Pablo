    # Знаменатель вслух: «все строки с именем экрана» ничего не значит, если
    # строк осталось три.
    assert len(names) >= 100 and len(named) >= len(names) - 5, (
        f"имя экрана несёт {len(named)} строк из {len(names)} — разбор `push` "
        "в теле открывашки сломан")


