def _modal_pass() -> str:
    """Тело прохода по окнам: от `for (const id of modalIds)` до его конца."""
    src = _src()
    i = src.index("for (const id of modalIds) {")
    depth, j = 0, i
    while j < len(src):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    return src[i : j + 1]


