"""Потолок: сколько маршрутов мини-аппа нельзя нажать ни на одном экране.

ОБРАТНАЯ СТОРОНА `test_miniapp_calls_have_routes`. Тот ловит «кнопка зовёт то,
чего на бэкенде нет» — 404/405, видимые как «кнопка не работает». Здесь другое
и дешевле, но ровно там, где работа СДЕЛАНА и НЕ ДОЕХАЛА до владельца: ручка
написана, проверена, скоупнута по владельцу — и ни один экран её не зовёт.
Владелец о такой функции не узнает никогда, а стоила она столько же.

Измерено 16.10.2026: 63 маршрута из 703. Целым блоком лежит витрина
провайдеров (`/api/miniapp/mp/*`, 12 маршрутов): бэкенд есть, экрана нет
вовсе. Рядом — шаблоны и экземпляры сетей, половина экспорта контактов и шесть
ручек рейтинга при живом экране «Рейтинг».

Доводить это до нуля — продуктовое решение владельца (каким экранам быть), а
не правка кода. Поэтому здесь потолок, а не запрет: новая ручка без экрана
число не увеличит молча, и никто больше не напишет бэкенд в пустоту, не
заметив. Снизили — опустите число здесь же, тем же коммитом.

ПОЧЕМУ НЕ СПИСОК ИМЁН. Список пришлось бы править при каждом переносе ручки
между модулями, а сторожит он то же самое — рост.
"""
from __future__ import annotations

import re
import sys

sys.path.insert(0, "tests")
from miniapp_source import api_files, miniapp_source  # noqa: E402

# Измерено 16.10.2026: было 63. Минус выгрузка операций — кнопка на экране
# была, но собирала CSV из разметки вместо этой ручки. Только вниз.
#
# 22.10.2026: 62 → 61. Минус /api/miniapp/campaign/launch: движок единой
# кампании (campaign_hub) был написан и покрыт тестами, а запустить его было
# нельзя — теперь у него есть экран. Это ровно тот случай, ради которого здесь
# потолок: бэкенд, о котором владелец не узнал бы никогда.
#
# Тем же заходом выяснилось, что число ЗАВЫШЕНО ещё на три: экспорт контактов
# (/api/miniapp/uch/export/{csv,vcf,json}) достижим, его зовёт openUchExport
# склейкой пути ('/api/miniapp/uch/export/' + f), а измеритель ищет путь
# целиком. Опускать потолок за счёт этих трёх нельзя — число должно
# соответствовать тому, что измеритель видит, иначе он перестанет сторожить
# рост. Поэтому они остаются в счёте как известная погрешность.
#
# 22.10.2026, тем же днём: 61 → 60. Минус /api/miniapp/uch/bulk/merge:
# пакетное объединение дублей контактов было написано (с проверкой владения
# обоими контактами) и недостижимо — экран объединял по одной паре за
# нажатие, сколько бы их ни нашлось.
CEILING = 60

_ROUTE = re.compile(
    r'app\.router\.add_(get|post|put|patch|delete)\(\s*"(/api/miniapp/[^"]+)"')


def _routes() -> list[tuple[str, str, str]]:
    out = []
    for p in api_files():
        src = p.read_text(encoding="utf-8")
        for m in _ROUTE.finditer(src):
            out.append((m.group(2), m.group(1).upper(), p.name))
    return out


def _unreachable() -> list[str]:
    """Маршруты, чьё неизменяемое начало пути не встречается в мини-аппе.

    Сравниваем по началу до первой подстановки (`/api/miniapp/account/{id}/x`
    → `/api/miniapp/account`), потому что фронт собирает такой путь шаблонной
    строкой и целиком его в исходнике нет. Поэтому измеритель СКЛОНЕН СЧИТАТЬ
    ручку достижимой — число ниже настоящего, и как потолок это честно: он
    стережёт рост, а не обещает полноту.
    """
    ui = miniapp_source()
    bad = []
    for path, method, where in _routes():
        head = path.split("{")[0].rstrip("/")
        if head and head not in ui:
            bad.append(f"{method} {path}  ({where})")
    return sorted(set(bad))


def test_the_detector_reads_both_sides():
    """Пустая таблица маршрутов или пустой мини-апп сделали бы тест зелёным."""
    routes = _routes()
    assert len(routes) > 600, f"разобрано всего {len(routes)} маршрутов"
    assert len(miniapp_source()) > 500_000, "исходник мини-аппа подозрительно мал"
    # Заведомо живой путь: экран аккаунтов зовёт его с самого начала.
    assert "/api/miniapp/accounts" in miniapp_source()


def test_the_detector_would_call_a_fresh_route_unreachable():
    """Проверка измерителя на заведомо недостижимом пути."""
    ui = miniapp_source()
    assert "/api/miniapp/этого-экрана-нет" not in ui


def test_the_number_of_unreachable_routes_only_shrinks():
    bad = _unreachable()
    assert len(bad) <= CEILING, (
        f"маршрутов, которых не нажать ни на одном экране, стало {len(bad)} "
        f"вместо {CEILING}. Новая ручка без экрана — работа, о которой владелец "
        f"не узнает: либо доведите её до экрана, либо осознанно поднимите "
        f"потолок в этом файле и объясните, зачем ручка без экрана нужна.\n  "
        + "\n  ".join(bad[-15:]))
    if len(bad) < CEILING:
        raise AssertionError(
            f"стало {len(bad)} — опустите CEILING в этом файле тем же коммитом, "
            f"иначе потолок перестанет сторожить рост")
