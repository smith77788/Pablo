"""Сборщик мусора не должен останавливать весь процесс на четверть секунды.

Бот, мини-апп и исполнитель операций живут в ОДНОМ процессе и в одном цикле
событий. Полная сборка мусора Python (поколение 2) обходит каждый живой объект
кучи, и пока она идёт, не отвечает никто: ни экран мини-аппа, ни кнопка бота,
ни пульс операции. После старта в куче около 275 тысяч объектов — модули,
функции, классы, обработчики, — и полная сборка по ним занимает 150–250 мс.
Случается она сама, по счётчику выделений: на стенде (2500 аккаунтов, 30 тыс.
диалогов) один проход по всем экранам мини-аппа дал восемь таких пауз,
1,6 секунды стоящего процесса в сумме.

Стартовые объекты живут до конца процесса, и обходить их на каждой сборке —
чистая потеря. `gc.freeze()` переносит всё, что есть в куче на этот момент, в
постоянное поколение, которое сборщик не обходит. На том же прогоне паузы
стали 10–45 мс, в сумме около 0,26 с.

Цена: если стартовый объект позже станет циклическим мусором, его память не
вернётся. На старте в куче модули и обработчики, которые и так живут вечно,
поэтому это приемлемо; замораживается ОДИН раз, а не периодически, чтобы в
постоянное поколение не уезжали данные запросов.
"""
from __future__ import annotations

import gc
import logging

log = logging.getLogger(__name__)


def freeze_startup_heap() -> int:
    """Собрать мусор старта и заморозить оставшееся. Вернуть число замороженных.

    Сначала полная сборка — иначе в постоянное поколение уехал бы и мусор
    старта, который уже никогда не освободится. Сбой здесь не должен мешать
    запуску: без заморозки процесс работает как раньше, только с паузами.
    """
    try:
        gc.collect()
        gc.freeze()
        n = gc.get_freeze_count()
        log.info("Сборщик мусора: заморожено %d стартовых объектов", n)
        return n
    except Exception:
        log.warning("Сборщик мусора: заморозка стартовой кучи не удалась",
                    exc_info=True)
        return 0
