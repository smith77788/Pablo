def section_by_key(key: str) -> Section | None:
    for s in SECTIONS:
        if s.key == key:
            return s
    return None


def intro_text() -> str:
    """Первый экран: что это, кому и из чего состоит."""
    blocks = "\n".join(f"{s.icon} <b>{s.title}</b> — {s.summary}" for s in SECTIONS)
    return (
        "✨ <b>Что такое Infragram</b>\n\n"
        f"{PITCH}\n\n"
        "<b>Кому это надо</b>\n"
        f"{FOR_WHOM}\n\n"
        "<b>Из чего состоит</b>\n"
        f"{blocks}\n\n"
        "<i>Нажмите раздел, чтобы посмотреть подробности.</i>"
    )


def section_text(section: Section) -> str:
    lines = "\n".join(f"• <b>{name}</b> — {what}" for name, what in section.items)
    return (
        f"{section.icon} <b>{section.title}</b>\n"
        f"<i>{section.summary}</i>\n\n"
        f"{lines}"
    )


def share_text(bot_username: str = "") -> str:
    """Готовое сообщение «перешли знакомому»: полное и самодостаточное.

    Пересылают ОДНО сообщение, поэтому здесь не разделы с кнопками, а связный
    текст: что это, кому и что умеет крупными блоками. Ссылка в конце — чтобы
    получатель мог открыть подробности сам, а не спрашивать снова.
    """
    blocks = "\n".join(
        f"{s.icon} <b>{s.title}</b> — {s.summary}" for s in SECTIONS
    )
    tail = (
        f"\n\n👉 Подробнее: https://t.me/{bot_username}?start=about"
        if bot_username else ""
    )
    return (
        "✨ <b>Infragram</b>\n\n"
        f"{PITCH}\n\n"
        "<b>Кому подойдёт</b>\n"
        f"{FOR_WHOM}\n\n"
        "<b>Что умеет</b>\n"
        f"{blocks}"
        f"{tail}"
    )
