"""Лечение аккаунта прямо в строке списка — кнопка вместо диагноза словами.

Список аккаунтов честно показывал состояние («🔑 Релог», «🛑 На паузе»,
«🔌 прокси не отвечает»), но НАЗЫВАЛ проблему, не давая её решить: чтобы
переавторизовать аккаунт, надо было открыть карточку, развернуть «Действия» и
найти нужную кнопку среди тринадцати. На флоте в 32 аккаунта это превращалось
в перебор карточек вручную.

Здесь — чистое ядро: строка аккаунта → одно самое полезное действие (или
ничего). Одно, а не список: строка списка не место для меню, а второй по
важности шаг всё равно виден в карточке.

Сдержанность — часть контракта:

* аккаунт **без прокси** не «сломан» — он работает с адреса хоста, это
  штатный режим (см. комментарий в `renderAccounts`); кнопку не показываем,
  иначе она висит на десятках строк и обесценивает остальные;
* **кулдаун** проходит сам — предлагать его сбросить значит предлагать обойти
  предохранитель флуда;
* аккаунт, **выключенный руками**, — не проблема, а решение владельца.
"""
from __future__ import annotations

# Действия, которые ведут в экран восстановления (одна дверь для «мёртвых»).
_REHAB = ("openRehab", [])


def _norm(v) -> str:
    return (v or "").strip().lower() if isinstance(v, str) else ""


def suggest(row) -> dict | None:
    """Строка аккаунта → одно действие вида
    ``{id, label, fn, args, tone, reason}`` или ``None``.

    Порядок правил — по «что мешает сильнее»: пока сессия не признана
    Telegram, чинить прокси или греть аккаунт бессмысленно.
    """
    try:
        acc_id = int(row["id"])
    except (TypeError, ValueError, KeyError, IndexError):
        return None
    try:
        status = _norm(row.get("acc_status"))
        health = _norm(row.get("health_status"))
        has_proxy = bool(row.get("has_proxy"))
        proxy_alive = row.get("proxy_alive")
    except AttributeError:  # не словарь — данные битые, молчим
        return None

    # 1. Сессия не признана Telegram: до релога не работает НИЧЕГО.
    if status == "session_expired":
        return {
            "id": "relog",
            "label": "🔑 Переавторизовать",
            "fn": "reauthAccount",
            "args": [acc_id],
            "tone": "warn",
            "reason": "Telegram не признаёт ключ авторизации — операции падают.",
        }

    # 2. Бан — аккаунт мёртв до апелляции; путь один, через восстановление.
    if status == "banned":
        return {
            "id": "rehab",
            "label": "🩺 Восстановление",
            "fn": _REHAB[0],
            "args": list(_REHAB[1]),
            "tone": "danger",
            "reason": "Аккаунт заблокирован — подайте апелляцию и следите за исходом.",
        }

    # 3. Спамблок снимается апелляцией в @SpamBot — отдельная короткая дверь.
    if status == "spamblock":
        return {
            "id": "appeal",
            "label": "🛡 Снять спамблок",
            "fn": "appealSpamblock",
            "args": [acc_id],
            "tone": "warn",
            "reason": "Спамблок ограничивает инвайты и ЛС — подайте апелляцию.",
        }

    # 4. Иммунная система держит аккаунт на паузе: он «активен», но операции
    #    его молча пропускают. Без кнопки это выглядело как «не работает».
    if health == "quarantine":
        return {
            "id": "rehab",
            "label": "🩺 Восстановление",
            "fn": _REHAB[0],
            "args": list(_REHAB[1]),
            "tone": "danger",
            "reason": "Иммунная система держит аккаунт на паузе — операции его пропускают.",
        }

    # 5. Прокси мёртв: аккаунт цел, но каждая операция падает по сети. Строго
    #    `is False` — непроверенный прокси (None) поломкой не считаем.
    if has_proxy and proxy_alive is False:
        return {
            "id": "fix_proxy",
            "label": "🔌 Заменить прокси",
            "fn": "openAccProxy",
            "args": [acc_id, None],
            "tone": "danger",
            "reason": "Прокси не отвечает — аккаунт цел, менять надо IP.",
        }

    # 6. Под риском (флуды/ограничения в анамнезе) — прогрев снижает риск бана.
    if health == "at_risk":
        return {
            "id": "warmup",
            "label": "🔥 Прогреть",
            "fn": "openWarmup",
            "args": [],
            "tone": "warn",
            "reason": "Были ограничения или флуды — прогрев снижает риск блокировки.",
        }

    return None


def annotate(rows) -> list:
    """Проставляет полю `fix` каждой строки её действие. Возвращает тот же
    список — вызывается на горячем пути списка аккаунтов, поэтому ничего не
    копирует и не роняет ответ при битой строке."""
    for r in rows or []:
        try:
            act = suggest(r)
        except Exception:  # pragma: no cover — список важнее подсказки
            act = None
        if act:
            r["fix"] = act
    return rows
