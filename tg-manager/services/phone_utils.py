"""Нормализация телефонного номера — единый алгоритм для мини-аппа и бота.

Пользователь вправе ввести номер как привык: с пробелами, дефисами, скобками,
с «+» или без. Приводим к каноничному «+<цифры>». `None` — если цифр не 7..15
(тогда честная ошибка в UI).

ОДИН источник истины: и форма мини-аппа, и FSM бота обязаны звать ЭТО. Иначе
валидации разъезжаются — «в одном месте номер принимает, в другом нет».
"""
from __future__ import annotations

import re


def normalize_phone(raw: str) -> str | None:
    digits = re.sub(r"\D", "", raw or "")
    if len(digits) < 7 or len(digits) > 15:
        return None
    return "+" + digits
