"""Инвайт: решения о восстановлении — не терять ёмкость и не терять цель.

Два разрыва, найденных на живом прогоне (203/380, 2ч 7м, флот 32 аккаунта):

1. ЦЕЛЬ ТЕРЯЛАСЬ. Стоп-кран «флот перегрет» останавливал операцию и при этом
   ЗАПРЕЩАЛ планировать продолжение — остаток целей (177) просто исчезал вместе
   с операцией. Пользователь должен был сам вспомнить и запустить заново. При
   этом сам отчёт советовал «дайте им отдохнуть и повторите позже»: продукт знал
   правильное действие, но не делал его. А PeerFlood/FloodWait — именно
   ВРЕМЕННЫЕ лимиты, которые лечатся отдыхом, в отличие от закрытой группы или
   поголовно мёртвых сессий.

2. ЁМКОСТЬ ТЕРЯЛАСЬ. Выдача прав «на лету» безправному инвайтеру допускалась
   РОВНО ОДИН раз на аккаунт (анти-цикл был множеством, а не счётчиком). Одна
   осечка по таймауту или флуду промоутера — и аккаунт выводился из круга на
   весь прогон. На отчёте это «3 аккаунтов без прав админа выведены из круга».

Здесь только решения — без сети и без базы, поэтому проверяемы напрямую.
"""
from __future__ import annotations

import re

# Сколько раз пробуем выдать права одному инвайтеру по ходу прогона.
# Одна попытка — слишком хрупко: промоут идёт через сеть (join + promote), и
# любой таймаут стоил аккаунта на весь прогон. Три — потолок против зацикливания
# на аккаунте, которому права выдать в принципе нельзя.
MAX_PROMOTE_ATTEMPTS = 3

# "admins_too_much" (лимит чата на число админов исчерпан) — это НЕ временный
# сетевой сбой, а ожидание своей очереди на ротацию места (см. op_worker
# _exec_mass_invite: место освобождается, когда другой аккаунт отрабатывает
# свой батч). Место может освободиться нескоро — трёх попыток по духу «сеть
# моргнула» здесь мало, аккаунт потерялся бы из круга раньше, чем реально
# подошла его очередь. Кап всё равно нужен — против вечного ожидания в чате,
# где лимит никогда не освободится (например, если демоут падает по правам).
MAX_ADMIN_SEAT_WAIT_ATTEMPTS = 30


def promote_retry_allowed(attempts_so_far: int,
                          max_attempts: int = MAX_PROMOTE_ATTEMPTS) -> bool:
    """Можно ли ещё раз попытаться выдать права этому инвайтеру.

    Считаем ПОПЫТКИ, а не факт «уже пробовали»: сорвавшийся по сети промоут не
    должен стоить аккаунта на весь прогон.
    """
    try:
        n = int(attempts_so_far or 0)
    except (TypeError, ValueError):
        n = 0
    return n < max(1, int(max_attempts or 1))


def should_schedule_continuation(
    *,
    left: int,
    group_broken: bool,
    all_failed_connect: bool,
    chain: int,
    max_chain: int,
    flood_storm: bool = False,
    ok_count: int = 0,
) -> tuple[bool, str]:
    """Планировать ли продолжение на остаток целей. (планировать, причина).

    Про перегрев флота правило СТАЛО ТОЧНЕЕ, а не мягче. Раньше любой перегрев
    отменял продолжение, и остаток целей исчезал вместе с операцией. Но перегрев
    бывает двух разных природ:

      • флот отработал и упёрся в потолок (много успехов, затем серия флудов) —
        это временный лимит Telegram, он снимается отдыхом. Бросать здесь цель
        неправильно: остаток уезжает на следующий запуск, когда аккаунты
        отдохнут, и там заново отработают все проверки (карантин, кулдауны,
        живость). Именно это продукт и советовал пользователю словами;

      • флот встал сразу, не добавив НИКОГО — это признак флагнутого чата или
        отравленной аудитории, а не усталости. Повтор здесь только жжёт
        аккаунты, поэтому продолжение не планируем и зовём человека.

    Остальные отмены прежние — там повтор бесполезен или вреден:
      • группа недоступна/закрыта — завтра будет то же самое;
      • ни один аккаунт не подключился — те же мёртвые сессии упадут так же;
      • исчерпан лимит цепочки — иначе операция размножалась бы бесконечно.
    """
    if int(left or 0) <= 0:
        return False, "остатка целей нет"
    if group_broken:
        return False, "группа недоступна — повтор не поможет"
    if all_failed_connect:
        return False, "ни один аккаунт не подключился — нужны живые сессии"
    if int(chain or 0) >= int(max_chain or 0):
        return False, "исчерпан лимит продолжений"
    if flood_storm:
        if int(ok_count or 0) <= 0:
            return False, ("флот перегрет, не добавив никого — похоже на флагнутый "
                           "чат или аудиторию; повтор только сожжёт аккаунты")
        return True, "флот перегрет — остаток уедет на следующий запуск, когда аккаунты отдохнут"
    return True, "остаток уедет на следующий запуск"


# Третий разрыв, найденный на живом прогоне (операция #90, флот 51, "не ответили
# (сессия/сеть): 43"): «не подключился» — единая непрозрачная корзина. Отчёт
# показывал оператору голое число без единого намёка на причину, хотя сам текст
# исключения (errors[]) уже лежал в _noconnect_errs — просто нигде не считался
# по типам, только искался на 2 конкретные подстроки для одной подсказки.
# Мёртвая сессия («переавторизуйте») и мёртвый/нестабильный прокси («назначьте
# другой прокси») требуют РАЗНЫХ действий оператора — свалены в одно число,
# отчёт не мог их различить, и 40+ реально нерабочих аккаунтов раз за разом
# получали новую попытку вместо диагностируемой причины.
