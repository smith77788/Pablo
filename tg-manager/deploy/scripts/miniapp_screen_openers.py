#!/usr/bin/env python3.12
"""Список функций мини-аппа, открывающих экран без аргументов — по одной в строку.

Нужен режиму `sweep` у `deploy/scripts/render_miniapp.mjs`: прежде он умел
проверять только пять вкладок, а экранов, которые открываются одним вызовом,
в приложении 114. Список строится из исходника, а не поддерживается руками:
руками он разошёлся бы с кодом ровно так же, как любая перепись по рукописному
списку (о чём в CLAUDE.md есть отдельный разбор).

Открывающей считается функция, в теле которой есть `push('s-…')` — именно так
мини-апп показывает экран.

Функции с обязательными аргументами (до четырёх) тоже идут в список — строкой
вида `имя|1` или `имя|1|1`. Обход пробует сначала с подставленными значениями,
а если экран не открылся — без них: единственный параметр у целого семейства
открывашек зовётся `keep` и означает «догрузить страницу, экран не открывать». Раньше их отбрасывали «нечем позвать вслепую», и обход показывал 111
экранов из 185: треть приложения не мерилась, а отчёт об этом молчал. Звать их
есть чем: заглушка отдаёт одни и те же данные на любой URL, так что экран
детали рисуется при любом id. Обход помечает такой вызов как пробный — если
функция упадёт на подставленном аргументе, это не находка, а просто непокрытый
экран, и он виден в строке охвата.

Формат строки: `имя[|1…][ s-экран]`. Хвост после пробела — экран, который
открывашка показывает своим `push`; обход засчитывает попытку, только когда на
виду оказался именно он.

Использование:
    python3.12 deploy/scripts/miniapp_screen_openers.py > /tmp/openers.txt
    node deploy/scripts/render_miniapp.mjs sweep /tmp/openers.txt
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2] / "mini_app"
_FN = re.compile(r"(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)")
_PUSH = re.compile(r"push\(\s*['\"](s-[\w-]+)['\"]")


def _body(src: str, start: int) -> str | None:
    i = src.find("{", start)
    if i < 0:
        return None
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i:j + 1]
    return None


def _params(raw: str) -> list[str]:
    return [p.strip() for p in raw.split(",") if p.strip()]


#: Параметр с таким именем — НЕ идентификатор, а флаг «догрузить страницу,
#: экран не открывать». Подставить в него единицу значит попросить экран не
#: открывать; обход тогда падал на запасной вызов без аргументов, и экран
#: рисовался с пустым заголовком («← 💬 undefined»). Имя параметра — часть его
#: смысла, и подстановка по типу молча меняет вызов на другой.
_FLAGS = {"keep"}


def _required(params: list[str]) -> list[str]:
    """Имена обязательных аргументов: со значением по умолчанию — не в счёт."""
    return [p for p in params if "=" not in p and not p.startswith("...")]


def openers() -> list[str]:
    files = [ROOT / "index.html"] + sorted((ROOT / "screens").glob("*.js"))
    out: list[str] = []
    for f in files:
        src = f.read_text(encoding="utf-8")
        for m in _FN.finditer(src):
            need = _required(_params(m.group(2)))
            if len(need) > 4:
                continue                      # чем заполнить пятый — неизвестно
            body = _body(src, m.end() - 1)
            if not body:
                continue
            want = sorted({p for p in _PUSH.findall(body)})
            if not want:
                continue
            # Хвостовые флаги не подставляем вовсе: пусть придут undefined.
            while need and need[-1] in _FLAGS:
                need.pop()
            call = m.group(1) + "|1" * len(need)
            # Имя экрана, который открывашка показывает СВОИМ `push`. Обход без
            # него засчитывал чужую работу: `openSalesManager(1)` с
            # подставленным id уходит сразу в редактор менеджера, экран
            # появился — значит «открылось», и `s-sales` оставался непокрытым,
            # хотя попытка числилась удачной. Знание ожидаемого экрана делает
            # числитель честным и заодно даёт обходу повод попробовать вызов
            # без аргументов, когда подставленный id увёл не туда.
            #
            # Если `push` в теле не один — экран зависит от данных, и обещать
            # обходу нечего: строка уходит без имени.
            out.append(f"{call} {want[0]}" if len(want) == 1 else call)
    return out


if __name__ == "__main__":
    names = openers()
    if not names:
        print("не найдено ни одной открывающей функции — сломан разбор, "
              "а не приложение", file=sys.stderr)
        raise SystemExit(2)
    print("\n".join(names))
