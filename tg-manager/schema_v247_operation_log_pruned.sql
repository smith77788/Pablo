-- Отметка «журнал целей этой операции убран».
--
-- Идемпотентность повтора стоит на `operation_log`: completed_targets и
-- completed_steps считают сделанным то, что есть в журнале. Уборка чистила
-- журнал по одному возрасту (30 дней), не глядя на статус операции. Значит у
-- недоведённой операции, которую владелец ещё может повторить кнопкой, журнал
-- молча исчезал, и повтор делал ВСЮ работу заново: те же приглашения тем же
-- людям (риск бана), второй пост в канал, второе сообщение человеку.
--
-- Тот же разрыв уже закрыт у рассылок (`broadcasts.delivery_log_pruned`):
-- уборка сначала помечает, и только потом удаляет строки, а повтор по
-- помеченной рассылке отказывает. Здесь — то же решение для операций.
ALTER TABLE operation_queue ADD COLUMN IF NOT EXISTS journal_pruned BOOLEAN NOT NULL DEFAULT FALSE;
