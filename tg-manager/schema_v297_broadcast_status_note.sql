-- schema_v297: причина состояния рассылки, видимая владельцу.
--
-- ЧТО БЫЛО. Рассылка заканчивалась «Ошибка» или «0 отправлено / 1 000 ошибок»,
-- а причина (отозван токен, бота заблокировали, Telegram недоступен и
-- рассылка ждёт докатки) жила только в логе сервера.
--
-- ЧТО ЗДЕСЬ. broadcasts.status_note — короткая причина по-русски: почему
-- рассылка ждёт, остановилась или кому не дошла. NULL — пояснять нечего.
ALTER TABLE broadcasts ADD COLUMN IF NOT EXISTS status_note TEXT;
