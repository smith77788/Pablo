-- Сетевой блип не убивает воронку человеку навсегда.
--
-- `auto_funnel._process_due_runs` на ЛЮБОМ исключении из обработки шага писал
-- `status='error'`, а само исключение уходило в `log.debug`. Постоянные
-- причины `_process_run` разбирает сам (нет шага → completed, нет токена →
-- error), поэтому наружу вылетает ровно транзиентное: блип БД, таймаут
-- Telegram, пул занят. Один такой блип — и воронка этому подписчику
-- заканчивалась молча и насовсегда.
--
-- `fail_count` — счётчик подряд идущих срывов. Пока он не исчерпан, запуск
-- остаётся 'active' и отодвигается на четверть часа; исчерпан — тогда
-- 'error', но уже громко и по делу. Успешный шаг обнуляет счётчик.
--
-- Аддитивно: DEFAULT 0 даёт прежнее поведение для уже идущих воронок.
ALTER TABLE auto_funnel_runs ADD COLUMN IF NOT EXISTS fail_count INT DEFAULT 0;
