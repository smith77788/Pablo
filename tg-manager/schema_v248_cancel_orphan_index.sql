-- Отменённые операции без итога — выборка уборщика `op_worker._watchdog_cancelled_orphans`.
--
-- Запрос идёт раз в минуту в цикле сторожей и почти всегда возвращает ноль
-- строк: такие операции появляются только когда процесс умер между нажатием
-- «Отменить» и сворачиванием исполнителя. Без частичного индекса этот ноль
-- стоил бы полного перебора очереди каждую минуту — на зрелой таблице это
-- сотни тысяч строк впустую.
--
-- Предикат повторяет условие уборщика ровно, поэтому индекс остаётся почти
-- пустым: строка выпадает из него, как только итог дописан.
CREATE INDEX IF NOT EXISTS idx_operation_queue_cancel_orphans
    ON operation_queue(finished_at)
 WHERE status = 'cancelled' AND result IS NULL;
