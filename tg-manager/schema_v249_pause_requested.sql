-- Пауза владельца, которая переживает рестарт воркера.
--
-- «Пауза» в мини-аппе переводит pending → paused, а уже ИДУЩУЮ операцию
-- сознательно не трогает: прервать её на полпути без чекпоинта означало бы
-- пере-прогон и дубли реальных действий. Но как только текущий проход
-- заканчивается сам (деплой Railway, сброс зависшей, отсрочка по флуд-паузе),
-- операция возвращается в очередь со status='pending' — и воркер запускает её
-- ЗАНОВО, хотя владелец нажал паузу. То есть аварийный тормоз продукта
-- отпускался ровно в тот момент, когда операцию наконец можно было
-- остановить безопасно.
--
-- Флаг хранит НАМЕРЕНИЕ владельца отдельно от статуса: статус описывает, где
-- операция сейчас, а pause_requested — что с ней делать на следующем входе в
-- работу. Снимает его только возобновление («Старт»).
ALTER TABLE operation_queue
    ADD COLUMN IF NOT EXISTS pause_requested BOOLEAN NOT NULL DEFAULT FALSE;

-- Поллер на каждом тике переводит помеченные ожидающие операции в 'paused'.
-- Частичный индекс держит этот проход дешёвым на длинной очереди.
CREATE INDEX IF NOT EXISTS idx_operation_queue_pause_requested
    ON operation_queue(id)
 WHERE pause_requested AND status = 'pending';
