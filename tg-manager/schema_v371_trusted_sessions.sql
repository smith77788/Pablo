-- schema_v371: доверенные (свои) сеансы аккаунта.
--
-- Дозор угона (services/session_watch) считает чужим КАЖДЫЙ сеанс, кроме
-- нашего. Но «чужой» сеанс часто свой же: тот же аккаунт открыт на телефоне
-- владельца, на втором устройстве, в десктопе. Владелец видел вечную тревогу
-- «🚨 Чужих сеансов: 1», а автозащита (если включена) закрыла бы его
-- собственный вход.
--
-- trusted_session_hashes — отпечатки сеансов, которые владелец пометил «это я».
-- Их дозор не считает чужими, тревога о них не приходит, автозащита их не
-- закрывает. Отпечаток тот же, что в account.getAuthorizations (BIGINT hash),
-- что и у foreign_session_hashes.
ALTER TABLE tg_accounts ADD COLUMN IF NOT EXISTS trusted_session_hashes BIGINT[];
