-- schema_v299: бюджет живучести считает воскрешения БЕЗ ПРОДВИЖЕНИЯ.
--
-- ЧТО БЫЛО. `operation_queue.revive_count` росла на каждом воскрешении и не
-- обнулялась никогда, а на `_MAX_REVIVES` (по умолчанию 3) операция гасилась
-- как «ядовитая». Воскрешение при этом случается не только от ядовитой
-- операции: рестарт процесса возвращает в очередь ВСЁ, что было в работе, а
-- деплой здесь едет на каждый пуш в рабочую ветку.
--
-- То есть длинная честная операция (инвайт идёт часами, потолок прогона — 6
-- часов) переживала три деплоя и получала «❌ Остановлена: 3 раз(а)
-- прерывалась». Владельцу при этом писали «прерывалась и НЕ ПРОДВИГАЛАСЬ» —
-- слово, которого код не проверял ни разу.
--
-- ЧТО ЗДЕСЬ. Два счётчика вместо одного:
--
--   revive_mark  — высшая отметка `done_items` по всем прогонам. Воскрешение
--                  обнуляет `done_items`, поэтому без отметки «продвинулась
--                  ли она с прошлого раза» спросить не у чего;
--   revive_total — сколько всего раз операцию воскрешали. Абсолютный предел:
--                  операция, которая делает одну цель и снова роняет воркер,
--                  иначе жила бы вечно, обнуляя счётчик подряд идущих.
--
-- `revive_count` остаётся, но теперь это ПОДРЯД ИДУЩИЕ воскрешения без
-- продвижения: сделала хоть одну новую цель — счётчик обнулён.
ALTER TABLE operation_queue ADD COLUMN IF NOT EXISTS revive_mark INT NOT NULL DEFAULT 0;
ALTER TABLE operation_queue ADD COLUMN IF NOT EXISTS revive_total INT NOT NULL DEFAULT 0;
