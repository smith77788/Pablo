-- schema_v361: «Разведка рекламы» помнит удалённую рекламу.
--
-- Повторный скан удалял из журнала ВСЕ рекламные посты, которых не нашёл в
-- свежей выдаче, — и переразмеченные, и просто удалённые каналом. А удаление
-- через сутки — это и есть формат размещения «1/24» (или «2/48»): рекламодатель
-- заплатил, пост отстоял срок и исчез. Журнал терял именно такие размещения,
-- счётчики рекламодателя падали, а цена канала считалась по неполной картине.
-- Теперь пост остаётся с отметкой, когда его не стало.
ALTER TABLE ad_posts_log ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;
