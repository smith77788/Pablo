-- schema_v230: индекс restriction_events по аккаунту, под риск-пульс.
--
-- `infra_memory.is_account_quarantined` читается ПЕРЕД каждым действием
-- каждого аккаунта (сорок с лишним мест: инвайты, рассылки, прогрев,
-- публикации) и считает серьёзные ограничения этого аккаунта за последние
-- трое суток. `get_account_health` делает то же самое подзапросом на каждый
-- аккаунт владельца.
--
-- Индексов на таблице было три, и все ведут либо по owner_id, либо по
-- created_at. По account_id — ни одного, поэтому проверка карантина читала
-- ВСЕ события платформы за окно и отбрасывала чужие фильтром. Рядом лежащий
-- account_flood_log, который тот же пульс читает так же, индекс
-- (account_id, created_at DESC) имеет — здесь его просто забыли.
--
-- Замер на живом Postgres, 150 000 событий на 3000 аккаунтов: 6.5 мс против
-- 0.5 мс на проверку, стоимость плана 5393 против 20. Умножается на число
-- действий массовой операции.
--
-- Порядок колонок (account_id, created_at): равенство по аккаунту, затем
-- диапазон по времени.

CREATE INDEX IF NOT EXISTS idx_restriction_events_account_created
    ON restriction_events (account_id, created_at);
