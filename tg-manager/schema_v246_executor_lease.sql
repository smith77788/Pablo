-- Аренда ИСПОЛНИТЕЛЯ операций: очередь разбирает ровно один процесс.
--
-- Лимиты флуда, потолки параллельности на владельца и троттлы восстановления
-- живут в ПАМЯТИ процесса. Две реплики с ролью worker считают их независимо,
-- суммарный темп по флоту выходит за безопасный — это прямой риск бана, то есть
-- самая дорогая поломка продукта. До сих пор это только писалось в лог
-- (services/replica_guard), а лог владелец не читает.
--
-- Строка здесь одна (id=1). Кто её держит — разбирает очередь; остальные ждут и
-- берут аренду, когда срок истёк (процесс умер) или её отпустили при плановой
-- остановке. Вторая реплика при этом остаётся живой: она продолжает отдавать
-- мини-апп и бота, просто не исполняет операции.
CREATE TABLE IF NOT EXISTS executor_lease (
    id          SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    worker_id   TEXT NOT NULL,
    role        TEXT NOT NULL DEFAULT 'all',
    acquired_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    renewed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL
);
