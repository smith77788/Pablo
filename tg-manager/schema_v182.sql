-- Предохранитель операций (circuit breaker) — в БД вместо памяти процесса.
--
-- ЗАЧЕМ (находка аудита №3, «глобалы, которые несут корректность»). Счётчик
-- сбоев и факт срабатывания жили в `op_worker._circuit_breaker_state` — обычном
-- словаре уровня модуля. Пока процесс был один, это работало. После разделения
-- ролей (INFRAGRAM_ROLE=web|worker) и при нескольких воркерах предохранитель
-- ломается ровно там, где он нужнее всего:
--   • каждая реплика считает сбои ОТДЕЛЬНО — порог «3 подряд» превращается в
--     3×N, то есть флот жжёт аккаунты втрое дольше, прежде чем встать на паузу;
--   • сработавший на реплике A предохранитель НЕ останавливает реплику B — она
--     продолжает запускать операции того же владельца в тот же шторм FloodWait;
--   • мини-апп (роль web) читает состояние из СВОЕЙ памяти, где оно всегда
--     пустое, и показывает «всё в порядке», пока воркер стоит на паузе.
--
-- Теперь состояние — одна строка на владельца, общая для всех процессов.
-- Решение принимается под блокировкой строки (SELECT ... FOR UPDATE), поэтому
-- два воркера, завершившие операции одновременно, дают +2 к счётчику, а не +1.

CREATE TABLE IF NOT EXISTS op_circuit_breaker (
    owner_id       BIGINT PRIMARY KEY,
    failures       INT NOT NULL DEFAULT 0,
    tripped_at     TIMESTAMPTZ,
    cooldown_until TIMESTAMPTZ,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Единственный «широкий» запрос — выбрать владельцев на активной паузе
-- (диагностика/наблюдаемость). Частичный индекс: строк с открытой цепью мало.
CREATE INDEX IF NOT EXISTS idx_op_circuit_breaker_open
    ON op_circuit_breaker (cooldown_until)
    WHERE tripped_at IS NOT NULL;
