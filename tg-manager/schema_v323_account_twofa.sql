-- schema_v323: пароль 2FA, поставленный оформлением, хранится у аккаунта.
--
-- Экран «Оформление» ставит пароль двухфакторной защиты сразу на десятки
-- аккаунтов, и до этой миграции пароль не сохранялся нигде: потерял — потерял
-- аккаунты при первом перелогине. Здесь он лежит зашифрованным
-- (token_vault, AES-256-GCM), им же исполнитель меняет и снимает 2FA без
-- ввода «текущего пароля» по каждому аккаунту.
ALTER TABLE tg_accounts ADD COLUMN IF NOT EXISTS twofa_enc TEXT;
