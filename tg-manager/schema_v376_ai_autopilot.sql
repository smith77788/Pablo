-- schema_v376: автопилот ИИ-ассистента.
--
-- Файл заводился как schema_v320_ai_autopilot.sql и столкнулся номером с
-- schema_v320_vlayer_rules.sql (новая коллизия версий запрещена,
-- tests/test_migration_repository_guard.py), а в манифест вписан не был.
-- Переименован в свободный номер. Повторный прогон безопасен: где колонка уже
-- есть (база, где выполнился файл со старым именем), ADD COLUMN IF NOT EXISTS
-- ничего не делает.
--
-- Владелец просил, чтобы ИИ реально запускал действия, а не только давал
-- черновики и ждал ручного подтверждения в чате. Флаг — на владельца, по
-- умолчанию FALSE: право на авто-пуск даёт только сам владелец (действия
-- ассистента запускают массовые операции). Снимается ровно шаг подтверждения:
-- все действия всё равно идут через те же пути (execute_action → operation_bus),
-- то есть канарейка/идемпотентность/карантин исполнителей сохраняются.
--
-- Отдельная колонка, а НЕ ключ в platform_users.settings_json: мини-апп
-- сохраняет settings_json целиком (перезапись), и флаг там затирался бы при
-- каждом сохранении настроек.
ALTER TABLE platform_users ADD COLUMN IF NOT EXISTS ai_autopilot BOOLEAN DEFAULT FALSE;
