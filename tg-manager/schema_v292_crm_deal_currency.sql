-- schema_v292: валюта у простой сделки (crm_deals).
--
-- Сделок в продукте было две системы: воронка контактов (contact_crm, валюта
-- у каждой строки) и простые сделки (crm_deals — их создают экран, сценарии,
-- автоответчик и коннекторы CRM). У простой сделки валюты не было вовсе, и
-- экран рисовал перед суммой «$» вручную — рублёвая сделка читалась долларовой.
-- Теперь обе системы показываются ОДНОЙ доской, а суммы на ней складываются
-- по валютам, поэтому валюта нужна каждой строке.
--
-- Старые строки остаются с NULL: это «основная валюта владельца» (её он и имел
-- в виду, вводя сумму), подставляется при чтении.
ALTER TABLE crm_deals ADD COLUMN IF NOT EXISTS currency TEXT;
