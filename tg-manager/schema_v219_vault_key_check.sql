-- schema_v219: канарейка ключа шифрования.
--
-- Зачем. Все секреты продукта лежат зашифрованными ОДНИМ ключом из
-- services/token_vault.py: строки сессий (tg_accounts, booster_sessions),
-- прокси с логином-паролем (user_proxies), токены ботов (bot_warehouse),
-- ключи SMM-панелей (smm_panels). Если ключ сменился, расшифровка падает не на
-- старте, а при первом обращении к КАЖДОЙ строке: аккаунты по одному
-- перестают подключаться, прокси «не работают», а в логе остаётся лишь
-- троттленное предупреждение token_vault раз в минуту. Снаружи это выглядит
-- как отказ Telegram, и настоящая причина ищется сутками.
--
-- Сменить ключ незаметно легче всего, когда TOKEN_ENCRYPTION_KEY не задан:
-- тогда ключ выводится из токена бота, и обычная ротация токена бота —
-- операция, к шифрованию отношения не имеющая, — обесценивает всё хранилище.
--
-- Что делает. Хранит одну строку: заранее известный текст, зашифрованный тем
-- же ключом. database.db.verify_vault_key на старте её расшифровывает. Не
-- сошлось — значит ключ не тот, и об этом говорится сразу и прямо.
--
-- Секрета в таблице нет: канарейка — шифротекст постоянной строки, по которому
-- ключ не восстанавливается.
CREATE TABLE IF NOT EXISTS vault_key_check (
    -- Строка ровно одна: проверяется один процесс шифрования, а не набор.
    id         INT PRIMARY KEY DEFAULT 1,
    canary     TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT vault_key_check_single_row CHECK (id = 1)
);

COMMENT ON TABLE vault_key_check IS
    'Канарейка ключа шифрования: постоянная строка под текущим ключом. Не расшифровалась на старте — ключ сменился, и все секреты в базе нечитаемы.';
