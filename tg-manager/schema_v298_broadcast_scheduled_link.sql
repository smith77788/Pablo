-- schema_v298: какая отложенная рассылка завела эту рассылку.
--
-- ЧТО БЫЛО. Связь «расписание → рассылка» жила ТОЛЬКО в
-- `scheduled_broadcasts.broadcast_id`, и писалась она отдельным запросом ПОСЛЕ
-- `create_broadcast`. Восстановление брошенных занятий
-- (`scheduler.recover_stuck_claims`) решает по этой колонке: пусто — значит
-- «работа не начиналась», возвращаем расписание в очередь.
--
-- В зазоре между двумя запросами утверждение неверно. Строка рассылки уже
-- создана и стоит в 'pending', а ровно эти рассылки на следующем старте
-- процесса поднимает `broadcaster.resume_interrupted` — то есть рассылка
-- УЙДЁТ. Расписание при этом вернётся в очередь и заведёт ВТОРУЮ рассылку на
-- ту же аудиторию: вся она получит сообщение дважды. Деплой на каждом пуше
-- делает этот зазор штатным событием, а не теорией.
--
-- ЧТО ЗДЕСЬ. Обратная ссылка на строке рассылки: она пишется ВМЕСТЕ с самой
-- строкой, одним INSERT, поэтому зазора у неё нет. Восстановление спрашивает
-- не вторую запись, а саму рассылку: «есть ли у этого расписания рассылка?».
ALTER TABLE broadcasts ADD COLUMN IF NOT EXISTS scheduled_id BIGINT;

-- Запрос восстановления: одна рассылка по id расписания. Частичный индекс,
-- потому что у рассылок, заведённых руками, колонка пуста.
CREATE INDEX IF NOT EXISTS idx_broadcasts_scheduled_id
    ON broadcasts (scheduled_id) WHERE scheduled_id IS NOT NULL;
