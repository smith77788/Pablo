"""Потолок на список кнопок в клавиатуре — и честная строка о том, что срезано.

Зачем. Экраны выбора строили по кнопке на каждый аккаунт (канал, бота) без
верхней границы. На платных тарифах число аккаунтов не ограничено, а Telegram
принимает reply_markup ограниченного размера: клавиатура из 10 кнопок весит
0,8 КБ, из 200 — 15 КБ, из 1000 — 75 КБ. То есть экран не «становится
неудобным» с ростом числа аккаунтов, он перестаёт открываться совсем, и человек
видит только ошибку. Ничего в коде этого не ловило: `bot/utils/target_selector.py`
умеет постраничность, но им не пользуется ни один экран.

Что делает. Отдаёт первые ``limit`` элементов и подпись о срезанном остатке.
Это НЕ замена постраничности: выбрать объект за потолком по-прежнему нельзя, и
подпись честно отправляет за полным списком в мини-апп, где есть поиск и
страницы. Но экран перестаёт ломаться, а умолчание перестаёт врать.

Использование::

    shown, note = cap_items(accounts)
    for acc in shown:
        kb.button(...)
    if note:
        text += "\\n\\n" + note
"""
from __future__ import annotations

from typing import Sequence, TypeVar

T = TypeVar("T")

# 40 кнопок — это 3 КБ разметки: втрое ниже порога, за которым Telegram начинает
# отказывать, и примерно столько человек готов пролистать на телефоне.
DEFAULT_LIMIT = 40


def cap_items(
    items: Sequence[T],
    limit: int = DEFAULT_LIMIT,
    what: str = "аккаунтов",
) -> tuple[Sequence[T], str]:
    """Первые ``limit`` элементов и подпись о срезанном остатке.

    Возвращает ``(показать, подпись)``. Подпись пустая, когда резать нечего —
    тогда и говорить не о чем.
    """
    total = len(items)
    if total <= limit:
        return items, ""
    hidden = total - limit
    return (
        items[:limit],
        f"⚠️ Показаны первые {limit} из {total} — ещё {hidden} не поместились. "
        f"Полный список {what} с поиском — в мини-аппе.",
    )


def cap_slice(items: Sequence[T], limit: int = DEFAULT_LIMIT) -> Sequence[T]:
    """Первые ``limit`` элементов — то, по чему строятся кнопки."""
    return items[:limit]


def cap_note_button(kb, items: Sequence[T], shown: Sequence[T], what: str = "acc") -> bool:
    """Дописать кнопку-подпись об остатке. Возвращает True, если дописала.

    Молчит, когда резать было нечего: лишняя строка в коротком списке — шум.
    """
    total, n = len(items), len(shown)
    if total <= n:
        return False
    from bot.callbacks import CapCb

    # Подпись короткая намеренно: часть экранов раскладывает кнопки в два-три
    # столбца (kb.adjust(2)/(3)), и длинный текст там обрезается многоточием.
    # Подробности человек получает по нажатию, отдельным всплывающим окном.
    kb.button(
        text=f"⚠️ Ещё {total - n} скрыто",
        callback_data=CapCb(total=total, shown=n, what=what),
    )
    return True


# Та же болезнь, что с клавиатурой, но в тексте: Telegram отвергает сообщение
# длиннее 4096 символов. Экран, клеящий строку на каждый объект, перестаёт
# открываться, когда объектов много. Строка ~60–80 символов, шапка съедает
# часть, поэтому 30 строк — с запасом, и ровно столько человек прочитает.
TEXT_LIMIT = 30


def cap_text(items: Sequence[T], limit: int = TEXT_LIMIT) -> Sequence[T]:
    """Первые ``limit`` элементов — то, по чему клеятся строки сообщения."""
    return items[:limit]


def cap_text_note(
    items: Sequence[T],
    shown: Sequence[T],
    what: str = "объектов",
) -> str:
    """Строка об остатке для вклейки в конец сообщения. Пустая, если не резали.

    В отличие от клавиатуры, тут подпись некуда нажать, поэтому она сразу
    говорит и сколько скрыто, и куда идти за полным списком.
    """
    total, n = len(items), len(shown)
    if total <= n:
        return ""
    return (
        f"\n<i>… и ещё {total - n} {what} — показаны первые {n}. "
        f"Полный список с поиском — в мини-аппе.</i>"
    )


def cap_text_append(
    lines: list,
    items: Sequence[T],
    shown: Sequence[T],
    what: str = "объектов",
) -> bool:
    """Дописать строку об остатке в список строк сообщения, если резали.

    Отдельная функция, а не голый ``lines.append(cap_text_note(...))``: та
    вернула бы пустую строку на коротком списке, и в сообщении появился бы
    висячий перенос.
    """
    note = cap_text_note(items, shown, what)
    if not note:
        return False
    lines.append(note)
    return True
