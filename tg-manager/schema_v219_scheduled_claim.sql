-- schema_v219: восстановление отложенных рассылок, брошенных на рестарте.
--
-- Зачем. Планировщик «занимает» строку расписания переводом в status='processing'
-- и снимает занятость только сам: пометив 'done' после успеха либо вернув
-- 'pending' в своём except. Если процесс умирает МЕЖДУ этими точками — а на
-- Railway это каждый деплой, — строка остаётся в 'processing' НАВСЕГДА:
-- get_pending_scheduled выбирает только 'pending', и ни один сторож такие строки
-- не смотрит. Отложенная рассылка молча не уходит и молча не отчитывается, а для
-- повторяемого расписания вместе с ней обрывается вся дальнейшая цепочка.
--
-- Вернуть такую строку в 'pending' вслепую нельзя: если процесс умер ПОСЛЕ
-- create_broadcast, повторный запуск создал бы ВТОРУЮ рассылку на всю аудиторию.
-- Поэтому два поля:
--
--   claimed_at   — когда строку заняли. Занятие живёт секунды, поэтому строка
--                  в 'processing' старше порога заведомо брошена.
--   broadcast_id — какая рассылка успела создаться. Есть id → рассылка
--                  существует, её докатит broadcaster.resume_interrupted (он
--                  пропускает уже доставленных по журналу, без дублей), и
--                  расписание надо закрыть как выполненное. Нет id → работа не
--                  начиналась, строку можно честно вернуть в очередь.
--
-- Аддитивно: у старых строк оба поля NULL, и сторож трактует их как «занятие
-- без отметки времени» — то есть тоже брошенные, но безопасные для возврата
-- (broadcast_id пуст).
ALTER TABLE scheduled_broadcasts
    ADD COLUMN IF NOT EXISTS claimed_at   TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS broadcast_id BIGINT;

COMMENT ON COLUMN scheduled_broadcasts.claimed_at IS
    'Когда планировщик занял строку (status=processing). Сторож по этому полю находит занятия, брошенные умершим процессом.';
COMMENT ON COLUMN scheduled_broadcasts.broadcast_id IS
    'Рассылка, созданная по этому расписанию. Отличает «работа не начиналась» от «рассылка уже создана» при восстановлении после рестарта.';

-- Сторож ходит только по занятым строкам — частичный индекс держит его дешёвым.
CREATE INDEX IF NOT EXISTS idx_scheduled_broadcasts_processing
    ON scheduled_broadcasts(claimed_at)
    WHERE status = 'processing';
