-- Сценарий и бот: поле на экране было, значение выбрасывалось.
--
-- ЧТО БЫЛО. Модальное окно создания сценария («🔄 Новый воркфлоу») показывает
-- выбор «Бот» и даже не открывается, пока список ботов не загружен
-- («❗ Сначала загрузите боты»), а в запрос кладёт `bot_id`. Обработчик этот
-- ключ не читал вовсе, и колонки под него не было: владелец выбирал бота,
-- нажимал «Создать», получал «✅ Воркфлоу создан» — и выбор исчезал без следа.
-- Тот же класс, что уже закрытый шаблон сценария: экран присылал `template`,
-- обработчик его не читал, и сценарий получался пустой при ответе «создан».
--
-- Колонка nullable: сценарий без бота — нормальный случай, селект предлагает
-- «Не привязан».
ALTER TABLE workflow_definitions ADD COLUMN IF NOT EXISTS bot_id BIGINT;

-- «Какие сценарии у этого бота» — единственный осмысленный запрос по колонке;
-- частичный индекс, потому что непривязанных сценариев может быть много.
CREATE INDEX IF NOT EXISTS idx_workflow_definitions_bot
    ON workflow_definitions (bot_id) WHERE bot_id IS NOT NULL;
