-- schema_v240: отметка «журнал доставки рассылки очищен».
--
-- broadcast_delivery_log — строка на каждого получателя каждой рассылки, и до
-- сих пор он не чистился вообще: у бота с десятью тысячами подписчиков одна
-- рассылка оставляет десять тысяч строк навсегда.
--
-- Просто вычистить по сроку нельзя. «Отправить недоставленным» считает
-- недоставленными тех, кого НЕТ в журнале (NOT EXISTS), поэтому исчезнувший
-- журнал означает: повторная отправка уйдёт ВСЕМ подписчикам заново, то есть
-- живым людям придёт спам. Поэтому у рассылки появляется отметка: журнал её
-- доставки удалён, повторная отправка по ней больше недоступна. Сводка
-- (sent_count / failed_count / total_users) лежит в самой broadcasts и
-- переживает уборку, так что отчёт по рассылке остаётся.
--
-- Колонка добавляется вперёд со значением по умолчанию: у всех существующих
-- рассылок журнал на месте, то есть FALSE — правда.

ALTER TABLE broadcasts
    ADD COLUMN IF NOT EXISTS delivery_log_pruned BOOLEAN NOT NULL DEFAULT FALSE;
