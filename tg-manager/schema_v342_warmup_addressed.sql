-- schema_v342: в разогреве на ответ человеку отвечает тот, к кому он обратился.
--
-- Человек отвечал на сообщение аккаунта «Олег», а следующий ход доставался
-- случайному аккаунту флота — и на вопрос, заданный Олегу, отвечала «Маша».
-- В живом чате так не бывает, и это первое, что замечают участники. Здесь
-- лежит аккаунт, к которому обратились: ход отдаётся ему, а не случайному.
ALTER TABLE chat_warmup_sessions ADD COLUMN IF NOT EXISTS addressed_acc BIGINT;
