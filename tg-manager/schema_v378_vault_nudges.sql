-- schema_v378: напоминания «подключите Хранилище диалогов» в личку.
--
-- Хранилище — одна из главных фишек продукта (решение владельца 21.11.2026),
-- и новичку, который его не подключил, бот напоминает о нём ровно дважды:
-- на второй и на седьмой день после регистрации (services/vault_nudge.py).
-- Здесь — сколько напоминаний уже ушло и когда последнее. Счётчик занимается
-- ДО отправки: потерянное напоминание дешевле второго такого же.
CREATE TABLE IF NOT EXISTS vault_nudges (
    owner_id    BIGINT      PRIMARY KEY,
    sent_count  INT         NOT NULL DEFAULT 0,
    last_sent_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
