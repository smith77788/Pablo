-- schema_v160: профильные факты аккаунта для расчёта риска инвайтинга.
--
-- Риск-движок уже умел учитывать возраст, заполненность имени/username и
-- уровень прогрева, но три сильных признака оставались за бортом ПОТОМУ ЧТО
-- их негде было взять: Premium и наличие аватара живут только в объекте `me`
-- из Telethon, а он до сих пор нигде не сохранялся. Считать их «по умолчанию»
-- было бы хуже, чем не считать вовсе: риск по выдуманным данным ведёт к
-- уверенным неверным решениям.
--
-- Колонки заполняются при обычной проверке здоровья аккаунтов — там `get_me()`
-- уже вызывается, так что дополнительной нагрузки на Telegram нет ни одной.
-- Все поля NULLable: NULL = «не проверяли», и риск-движок такой аккаунт НЕ
-- штрафует, а просто не применяет к нему эти факторы.

ALTER TABLE tg_accounts
    -- Telegram Premium у самого аккаунта. NULL = не проверяли.
    ADD COLUMN IF NOT EXISTS is_premium         BOOLEAN,
    -- Есть ли аватар. Пустой профиль без фото — классический спам-признак.
    ADD COLUMN IF NOT EXISTS has_photo          BOOLEAN,
    -- Когда профильные факты снимались. Нужен, чтобы отличать «проверено и
    -- False» от «не проверяли», и чтобы протухшие данные не считались свежими.
    ADD COLUMN IF NOT EXISTS profile_checked_at TIMESTAMPTZ;

-- Выборка «кого пора перепроверить» идёт по этой колонке.
CREATE INDEX IF NOT EXISTS idx_tg_accounts_profile_checked
    ON tg_accounts(profile_checked_at);
