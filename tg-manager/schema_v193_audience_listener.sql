-- schema_v193_audience_listener.sql — opt-in пассивный слушатель Update-потока.
-- Первопричина: весь проект узнаёт о входящих ЛС через polling (Business Vault
-- сравнение — единственное исключение, но оно работает только для аккаунтов,
-- подключённых через Telegram Business API, не для обычного флота tg_accounts).
-- MTProto — не request/response: сервер САМ пушит Updates в подключённую
-- сессию (так доставляются сообщения в любом официальном клиенте). Слушать
-- этот поток пассивно для чатов, где аккаунт и так состоит — не эксплойт, а
-- push вместо poll: меньше активных запросов → меньше флуд-сигналов → меньше
-- риска бана. Opt-in: слушатель держит соединение аккаунта открытым часами,
-- поэтому аккаунт становится недоступен для обычных операций всё это время —
-- это должен быть выделенный ресурс, а не совмещаться со всем флотом.
ALTER TABLE tg_accounts ADD COLUMN IF NOT EXISTS listener_enabled BOOLEAN NOT NULL DEFAULT FALSE;
