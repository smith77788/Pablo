-- Флаг «этот бот работает через вебхук», которого не было в схеме.
--
-- services/managed_bot_webhooks.restore_from_db читает
-- `WHERE is_active = true AND COALESCE(use_webhook, false) = true`, но колонки
-- не существовало: запрос падал, except писал строку в debug, и после каждого
-- перезапуска контейнера карта секретов вебхуков оставалась пустой. Входящие
-- обновления Telegram приходили с секретом, которого продукт уже не знал, и
-- отбрасывались с ответом 200 — то есть терялись молча. Ветка автодеплойная,
-- перезапуск здесь штатное событие.
--
-- Значение по умолчанию FALSE: поведение не меняется, ни один бот на вебхук
-- сам не переезжает. Колонка даёт функции выключатель, без которого её нельзя
-- ни включить, ни восстановить.
ALTER TABLE managed_bots ADD COLUMN IF NOT EXISTS use_webhook BOOLEAN DEFAULT FALSE;
