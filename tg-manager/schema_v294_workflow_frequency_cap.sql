-- schema_v294: предел сообщений человеку в сутки от всех сценариев бота.
--
-- ЧТО БЫЛО. Каждый сценарий считал только себя: приветствие, дожим,
-- рассылка по расписанию и возврат ушедших могли в один день написать одному
-- человеку восемь раз. Так бота блокируют и жалуются на спам.
--
-- ЧТО ЗДЕСЬ. workflow_definitions.max_per_day — сколько сообщений за сутки
-- человек может получить от ВСЕХ сценариев этого бота, прежде чем этот
-- сценарий подождёт. NULL — без предела (как раньше). Ответ человеку,
-- который прямо сейчас в чате, предел не держит.
ALTER TABLE workflow_definitions ADD COLUMN IF NOT EXISTS max_per_day INTEGER;
CREATE INDEX IF NOT EXISTS idx_workflow_runs_person
    ON workflow_runs (bot_id, chat_id);
