-- v195: метка «о смерти прокси уже сообщили».
--
-- Нужна сторожу прокси (services/proxy_watchdog): он раз в полчаса проверяет
-- активные прокси и ОДИН раз сообщает владельцу, что прокси умер и сколько
-- аккаунтов из-за этого простаивает. Без метки уведомление повторялось бы
-- каждые полчаса и его перестали бы читать. Когда прокси оживает, метка
-- снимается — о следующей смерти предупредим снова.
ALTER TABLE user_proxies
    ADD COLUMN IF NOT EXISTS dead_notified_at TIMESTAMPTZ;

-- Обход берёт только активные прокси и считает привязанные аккаунты.
CREATE INDEX IF NOT EXISTS idx_proxies_active
    ON user_proxies(is_active) WHERE is_active;
