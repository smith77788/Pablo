-- Шаг воронки не уходит человеку второй раз после рестарта.
--
-- `auto_funnel._process_run` отправлял сообщение шага и ТОЛЬКО ПОТОМ писал
-- продвижение (`next_step_num`/`next_send_at`). Между этими двумя действиями
-- процесс умирает на каждом деплое рабочей ветки: строка остаётся с тем же
-- next_step_num и next_send_at <= NOW(), поэтому следующий круг опроса
-- отправляет этот же шаг тому же живому человеку заново — и так на каждом
-- рестарте внутри окна.
--
-- `last_sent_step` — отметка «этот шаг уже отправлен», которую пишут ДО
-- отправки одним условным UPDATE (claim). Не прошёл claim — значит шаг уже
-- уходил, и повтор его пропускает. Потерянное сообщение воронки дешевле
-- второго: второе человек видит как спам, а бот — как повод для блокировки.
--
-- Аддитивно: NULL у всех существующих строк читается как «ничего не
-- отправлено», то есть прежнее поведение для уже идущих воронок.
ALTER TABLE auto_funnel_runs ADD COLUMN IF NOT EXISTS last_sent_step INT;
