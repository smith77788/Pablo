-- schema_v220: честный отсчёт ожидания свободных аккаунтов.
--
-- Зачем. Операция, не нашедшая свободных аккаунтов, мягко откладывается на 90
-- секунд и ждёт, пока флот освободится. Ждать ей разрешено _ACCT_WAIT_MAX_MIN,
-- после чего она честно проваливается — иначе получился бы вечный цикл.
--
-- Но отсчёт вёлся от created_at, то есть от МОМЕНТА ПОСТАНОВКИ, а не от начала
-- ожидания. Для операции, запускаемой сразу, разница незаметна. Для всего
-- остального она фатальна:
--
--   • отложенный пост, поставленный утром на вечер;
--   • очередной круг рекуррентного автопостинга;
--   • повтор после флуд-паузы (PeerFlood откладывает на 48 часов);
--   • операция, возвращённая в очередь предохранителем.
--
-- Все они к моменту запуска заведомо старше двадцати минут, поэтому ПЕРВАЯ же
-- встреча с занятым флотом проваливала их мгновенно, с текстом «не дождались
-- свободных аккаунтов» — хотя не ждали нисколько. Владелец видел отложенную
-- рассылку, упавшую ровно в назначенное время, без единой попытки.
--
-- Отдельная отметка нужна именно потому, что переиспользовать нечего:
-- scheduled_for каждое откладывание сдвигает вперёд, started_at обнуляется при
-- возврате в очередь, а retry_count тратится на повторы по ошибке исполнителя.
--
-- Аддитивно, NULL = «ожидание ещё не начиналось».
ALTER TABLE operation_queue
    ADD COLUMN IF NOT EXISTS acct_wait_since TIMESTAMPTZ;

COMMENT ON COLUMN operation_queue.acct_wait_since IS
    'Когда операция ВПЕРВЫЕ не нашла свободных аккаунтов. От этой отметки, а не от created_at, отсчитывается предел ожидания флота. Сбрасывается, как только исполнитель реально отработал.';
