-- Отметка о конфликте сессии (AUTH_KEY_DUPLICATED) — чтобы РАЗОВЫЙ конфликт не
-- парковал весь флот.
--
-- ЧТО ПРОИСХОДИЛО. Проверка здоровья при AUTH_KEY_DUPLICATED сразу ставила
-- аккаунту acc_status='cooldown'. Комментарий в коде честно говорит: «разовый
-- флап/мультидевайс не должен выключать флот» — но статус выставлялся с ПЕРВОГО
-- же раза. На свежем флоте из 39 аккаунтов один проход монитора пометил
-- cooldown ВСЕ 39. А cooldown исключает аккаунт из прогрева (account_warmer),
-- из иммунитета (immunity_engine) и портит оценку здоровья. Снаружи: «флот
-- свежий, не использовался, и не работает».
--
-- ТЕПЕРЬ. Первый конфликт только ЗАПОМИНАЕТСЯ (эта колонка) и пишется в лог —
-- статус не трогаем. Если конфликт повторяется на следующей проверке, значит он
-- устойчивый (сессия действительно живёт где-то ещё) — вот тогда cooldown с
-- объяснением, что делать. Успешная проверка отметку снимает.

ALTER TABLE tg_accounts
    ADD COLUMN IF NOT EXISTS session_conflict_at TIMESTAMPTZ;

-- «Кто сейчас в конфликте» — короткий список для разбора и для экрана аккаунтов.
CREATE INDEX IF NOT EXISTS idx_tg_accounts_session_conflict
    ON tg_accounts (owner_id)
    WHERE session_conflict_at IS NOT NULL;
